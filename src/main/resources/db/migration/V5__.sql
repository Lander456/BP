CREATE TABLE IF NOT EXISTS artifact
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name        VARCHAR(255),
    description VARCHAR(255),
    label_code  VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_artifact PRIMARY KEY (id),
    CONSTRAINT uc_artifact_label_code UNIQUE (label_code)
);

CREATE TABLE IF NOT EXISTS iris_sector
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    iris_map_id  BIGINT,
    name         VARCHAR(255),
    start_angle  DOUBLE PRECISION,
    end_angle    DOUBLE PRECISION,
    inner_radius DOUBLE PRECISION                        NOT NULL DEFAULT 0.0,
    outer_radius DOUBLE PRECISION                        NOT NULL DEFAULT 1.0,
    description  VARCHAR(255),
    CONSTRAINT pk_iris_sector PRIMARY KEY (id),
    CONSTRAINT fk_iris_sector_on_iris_map FOREIGN KEY (iris_map_id) REFERENCES iris_map (id)
);

CREATE TABLE IF NOT EXISTS iris_finding
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    iris_image_id    BIGINT,
    iris_sector_id   BIGINT,
    artifact_id      BIGINT,
    confidence_score DOUBLE PRECISION,
    is_generated     BOOLEAN,
    is_validated     BOOLEAN,
    geometry_json    TEXT,
    CONSTRAINT pk_iris_finding PRIMARY KEY (id),
    CONSTRAINT fk_iris_finding_on_iris_image FOREIGN KEY (iris_image_id) REFERENCES iris_image (id),
    CONSTRAINT fk_iris_finding_on_iris_sector FOREIGN KEY (iris_sector_id) REFERENCES iris_sector (id),
    CONSTRAINT fk_iris_finding_on_artifact FOREIGN KEY (artifact_id) REFERENCES artifact (id)
);
